-- 数字人对话最小数据模型。
--
-- 注：training_session 是「会话档案」表，命名沿用了早期脚手架，实际存的是对话会话（不是训练域）。
-- 评测/训练表（assessment）随训练域暂未迁入。
create table if not exists training_session (
    id            varchar(64) primary key,
    device_id     varchar(128),
    avatar_id     varchar(128),
    model         varchar(64),
    voice         varchar(128),
    status        varchar(32),
    started_at    bigint,
    ended_at      bigint,
    error_message varchar(512)
);

create table if not exists conversation_turn (
    id             bigint generated by default as identity primary key,
    session_id     varchar(64),
    seq            integer,
    user_text      varchar(4000),
    assistant_text varchar(4000),
    audio_path     varchar(512),
    latency_ms     bigint,
    created_at     bigint
);

create index if not exists idx_turn_session on conversation_turn (session_id, seq);
